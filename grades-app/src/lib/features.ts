/** Что показывать роли. Админ видит всё — чтобы знать, что видят остальные. */
export function forRole<T extends { roles?: FeatureRole[] }>(items: T[], role: FeatureRole): T[] {
  if (role === 'admin') return items;
  return items.filter((i) => !i.roles || i.roles.includes(role));
}

/** Запись с отфильтрованными под роль деталями. */
export function updatesFor(role: FeatureRole): FeatureUpdate[] {
  return forRole(UPDATES, role).map((u) => ({ ...u, details: forRole(u.details, role) }));
}

export function sectionsFor(role: FeatureRole): FeatureSection[] {
  return forRole(SECTIONS, role).map((s) => ({ ...s, items: forRole(s.items, role) }));
}
