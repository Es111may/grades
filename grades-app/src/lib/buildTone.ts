// Цвет точки билда — один источник для точки билда везде: лидерборд,
// канбан, 9-Box, поп-ап 360, матрица скиллов, грейды, оценки, портрет,
// «Экономика». Раньше одна и та же тернарка жила в десятке файлов.
//
// Чистый модуль без React и без зависимостей — точка билда есть почти на
// каждой странице, модуль едет в их First Load. Разметка точки и чипа —
// components/BuildChip.tsx. Названия билдов — из БД (`build.name`), в коде —
// BUILD_NAMES (lib/types) и NON_GRADING_BUILDS (lib/employment).

/** Нейтральная точка: токен темы — в тёмной светлее, в светлой темнее. */
export const NEUTRAL_DOT = 'rgb(var(--c-stone))';

/**
 * Цвет точки по коду билда. Хексы — прежние, одинаковые в обеих темах
 * (насыщенные точки читаются и на тёмном, и на белом).
 */
export const BUILD_DOT: Readonly<Record<string, string>> = {
  creator: '#00ca48', // Инхаус — зелёный
  visioner: '#7c3aed', // Криэйт — фиолетовый
  navigator: '#0ea5e9', // Импрув — голубой
  // Коммуникации (билд без грейдов) — свой нейтральный тон. Раньше код
  // проваливался в «иначе» и получал голубой Импрува — два разных билда
  // в списке выглядели одним.
  communications: NEUTRAL_DOT,
};

/** Цвет точки билда. Неизвестный или не заданный билд — нейтральный, а не чужой цвет. */
export function buildDotColor(code: string | null | undefined): string {
  return (code && BUILD_DOT[code]) || NEUTRAL_DOT;
}
