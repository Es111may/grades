/**
 * Импорт исторических 360-оценок лидов/стардизов.
 *
 * Для Phase 22 у нас в Google Form сырые CSV есть только с мая 2026.
 * Более ранние оценки (декабрь 2025 — март 2026) хранились как готовые
 * аналитические markdown-отчёты в Buildin — без сырых CSV. Чтобы
 * подтянуть их в систему как историю, мы вручную восстанавливаем
 * агрегаты из markdown и кладём в БД через этот скрипт.
 *
 * Скрипт:
 *   - запускается в start.ts после остальных миграций;
 *   - идемпотентен: проверяет наличие LeadReview по {targetUserId, period}
 *     — если есть, ничего не делает;
 *   - graceful: если лид не найден по имени, просто пропускает запись
 *     (не падает, чтобы не блокировать деплой).
 *
 * Тексты ответов в исторических отчётах не имели атрибуции роли
 * («Дизайнер X сказал...» — нет), поэтому всем ставим role='other'.
 * Это честнее, чем угадывать.
 */

import { Prisma, PrismaClient } from '@prisma/client';
import type { LeadReviewAggregates, ResponderRole } from '../src/lib/leadSurvey';

const prisma = new PrismaClient();

type HistoricalReview = {
  /** Подстрока для поиска лида/стардиза в БД по fullName. */
  targetNameLike: string;
  period: string;
  aggregates: LeadReviewAggregates;
  aiSummary?: string;
  cdoSummary?: string;
  /** Чтобы importedAt не выпрыгивал из истории и порядок циклов был
   *  правильный, ставим явную дату — день, когда отчёт был сформирован. */
  importedAt: Date;
};

/** Хелпер для упрощённого описания пункта без знания разбивки по ролям. */
function item(
  id: string,
  question: string,
  avg: number | null,
  answeredCount: number,
) {
  return {
    id,
    question,
    average: avg,
    averageByRole: {} as Partial<Record<ResponderRole, number | null>>,
    answeredCount,
  };
}

/** Тексты в исторических отчётах атрибутируются как «other» — без роли. */
function text(t: string) {
  return { role: 'other' as ResponderRole, text: t };
}

